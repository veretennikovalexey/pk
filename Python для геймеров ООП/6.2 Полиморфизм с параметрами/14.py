class Zombie:
    def attack(self, power): 
        print(f'Зомби бьёт игрока на {power} урона.')


class Skeleton: 
    def attack(self, power): 
        print(f'Скелет выпускает стрелу на {power} урона.')


class Creeper:
    def attack(self, power): 
        print(f'Крипер взрывается с силой {power}!')
